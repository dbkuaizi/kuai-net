/**
 * 把任意语言标识规范化成 LANGUAGES 里的 code。
 * 支持 "zh-CN"、"zh-TW"、"pt"、"pt-br" 这类浏览器语言写法。
 */
function resolveLang(input) {
  const raw = String(input || '').toLowerCase();
  if (!raw) return null;

  const exact = LANGUAGES.find((l) => l.code.toLowerCase() === raw);
  if (exact) return exact.code;

  // 繁体中文：zh-TW / zh-HK / zh-MO / zh-Hant…
  if (raw.startsWith('zh')) {
    return /hant|tw|hk|mo/.test(raw) ? 'zh-Hant' : 'zh';
  }
  if (raw.startsWith('pt')) return 'pt-BR';

  const base = raw.split('-')[0];
  const byBase = LANGUAGES.find((l) => l.code.toLowerCase() === base);
  return byBase ? byBase.code : null;
}

/** 浏览器首选语言，取第一个能识别的。 */
function detectLang() {
  const list = (navigator.languages && navigator.languages.length)
    ? navigator.languages
    : [navigator.language || ''];
  for (const item of list) {
    const code = resolveLang(item);
    if (code) return code;
  }
  return 'en';
}

/** 取语言对应的文案包，缺省回退英文。 */
function getTexts(code) {
  return I18N[code] || I18N.en;
}

/** 取 <html lang> 取值。 */
function langHtmlTag(code) {
  const opt = LANGUAGES.find((l) => l.code === code);
  return opt ? opt.html : 'en';
}
